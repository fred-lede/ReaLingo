const DICT = { zh, en, "zh-TW": zhTW };
export type Locale = keyof typeof DICT;
export type Key = keyof typeof zh;

/** What "system" picks: Traditional for zh-TW / zh-HK / zh-MO / zh-Hant, Simplified for other zh. */
export function detectSystem(): Locale {
  const nav = navigator.language;
  if (nav.startsWith("zh")) return /-(TW|HK|MO)|Hant/i.test(nav) ? "zh-TW" : "zh";
  return "en";
}

/** "system" resolves through `navigator.language`, like the desktop app always did. */
export const locale = computed<Locale>(() =>
  settings.uiLang === "system" ? detectSystem() : settings.uiLang
);

/** The name of the locale "Follow system" would pick, for the picker row. */
export function systemLocaleName(): string {
  const l = detectSystem();
  return l === "zh-TW" ? "繁體中文" : l === "zh" ? "简体中文" : "English";
}

const htmlLang = (l: Locale) => (l === "zh" ? "zh-CN" : l === "zh-TW" ? "zh-Hant" : "en");

export function setLocale(l: "system" | Locale) {
  settings.uiLang = l;
  document.documentElement.lang = htmlLang(locale.value);
}
watch(locale, () => { document.documentElement.lang = htmlLang(locale.value); }, { immediate: true });

export function t(key: Key): string {
  return DICT[locale.value][key] ?? DICT.zh[key] ?? key;
}

/** `t` with `{name}` placeholders: t("perm_pending", { n: 2 }) → "2 项权限未开启". */
export function tf(key: Key, vars?: Record<string, string | number>): string {
  let s = t(key);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
